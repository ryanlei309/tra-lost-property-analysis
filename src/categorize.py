def classify(name):
    """
    看一件遺失物的名字，判斷它的品類、價值層級、以及能不能追回失主。

    Input:
        name (str): 遺失物的品名字串，例如「黑色長傘」。

    Returns:
        一個 tuple (category, value_tier, recoverable)：
            category (str): 細類名稱，比對不到就是「其他」。
            value_tier (str): 價值層級「高／中／低」，比對不到是「未知」。
            recoverable (bool): 這類東西通常追不追得回失主。
    """
    # 先轉小寫，這樣英文關鍵字（iphone、usb…）大小寫都能比對到。
    n = (name or "").lower()

    # 規則由上往下比，命中第一條就回傳，所以順序有意義。
    for cat, kws, tier, recover in CATEGORY_RULES:
        if any(k.lower() in n for k in kws):
            return cat, tier, recover

    # 一條都沒中，回預設的「其他 / 未知 / 追不回」。
    return DEFAULT


def group_of(category):
    """
    把細類轉成大類。

    Input:
        category (str): 細類名稱，例如「交通票卡」。

    Returns:
        對應的大類名稱；查不到就回「其他」。
    """
    return CATEGORY_GROUP.get(category, "其他")


